"""The edge guard every host's proxy reads: one router, refusing /website/info.

Odoo answers ``/website/info`` to anyone, with the installed apps and the
version, and with a language in front too. The guard is a router of the
proxy's own, on ``https`` only, above every instance's router and below
the exception an instance can turn on and the direct entrypoint's refusal,
whose only middleware admits no address (owner's decision, 7-nov-2026).
"""
import ipaddress
import re

import yaml

from odoo.tests.common import TransactionCase

from odoo.addons.incubacloud.models.cloud_host_edge_guard import (
    EDGE_GUARD_FILE,
    EDGE_GUARD_PRIORITY,
    WEBSITE_INFO_EXCEPTION_PRIORITY,
    WEBSITE_INFO_RULE,
    edge_guard_digest,
)
from odoo.addons.incubacloud.models.deploy_instance_executor import (
    LOGIN_ROUTER_PRIORITY,
)

#: The document, exactly: what the render parses back to.
_EXPECTED = {
    "http": {
        "middlewares": {
            "ic-guard-deny": {
                "ipWhiteList": {"sourceRange": ["255.255.255.255/32"]},
            },
        },
        "routers": {
            "ic-guard-website-info": {
                "rule": (
                    "Path(`/website/info`) || PathPrefix(`/website/info/`)"
                    " || Path(`/{lang:[A-Za-z0-9_@-]{2,20}}/website/info`)"
                    " || PathPrefix(`/{lang:[A-Za-z0-9_@-]{2,20}}/website/info/`)"
                ),
                "priority": 2000,
                "entryPoints": ["https"],
                "middlewares": ["ic-guard-deny"],
                "service": "noop@internal",
                "tls": {},
            },
        },
    },
}


def _matches(path):
    """Whether the guard's rule matches *path*, read as Traefik v2 reads it.

    Each alternative becomes a regular expression: ``Path`` the whole
    path, ``PathPrefix`` its start, ``{name:re}`` the pattern given.
    """
    for kind, template in re.findall(r"(Path|PathPrefix)\(`([^`]*)`\)", WEBSITE_INFO_RULE):
        pattern = ""
        for literal, variable in re.findall(r"([^{]+)|(\{[a-z]+:(?:[^{}]|\{[^}]*\})+\})", template):
            pattern += re.escape(literal) if literal else f"(?:{variable.split(':', 1)[1][:-1]})"
        if re.fullmatch(pattern + ("(?:.*)" if kind == "PathPrefix" else ""), path):
            return True
    return False


class TestTheEdgeGuardDocument(TransactionCase):

    def setUp(self):
        super().setUp()
        self.document = self.env["cloud.host"]._shipped_edge_guard_yml()

    def test_it_parses_back_to_exactly_the_rule(self):
        self.assertTrue(self.document.startswith(
            "# Auto-generated by IncubaCloud. Do not edit by hand.\n",
        ))
        self.assertEqual(yaml.safe_load(self.document), _EXPECTED)

    def test_it_lives_where_no_tenant_slug_can_reach(self):
        """Sablier writes ``{slug}.yml`` beside it; a slug has no ``_``."""
        self.assertEqual(EDGE_GUARD_FILE, "~/traefik/dynamic/ic_guard.yml")

    def test_the_list_admits_nobody(self):
        ranges = yaml.safe_load(self.document)["http"]["middlewares"][
            "ic-guard-deny"]["ipWhiteList"]["sourceRange"]
        for entry in ranges:
            network = ipaddress.ip_network(entry)
            self.assertEqual(network.num_addresses, 1)
            self.assertTrue(network.network_address.is_reserved)

    def test_the_page_is_refused_bare_with_a_tail_and_behind_a_language(self):
        for path in (
            "/website/info", "/website/info/", "/website/info/anything",
            "/es/website/info", "/fr_FR/website/info", "/sr@latin/website/info",
            "/es/website/info/",
        ):
            with self.subTest(path=path):
                self.assertTrue(_matches(path))
        for path in (
            "/website", "/website/infos", "/web/login", "/website/information",
            "/e/website/info", "/es/shop", "/es/website/infos",
        ):
            with self.subTest(path=path):
                self.assertFalse(_matches(path))

    def test_it_stands_between_the_instances_and_the_direct_refusal(self):
        self.assertEqual(EDGE_GUARD_PRIORITY, 2000)
        self.assertGreater(EDGE_GUARD_PRIORITY, LOGIN_ROUTER_PRIORITY)
        # Sablier's -draining, the highest an instance's names get.
        self.assertGreater(EDGE_GUARD_PRIORITY, 1000)
        self.assertGreater(WEBSITE_INFO_EXCEPTION_PRIORITY, EDGE_GUARD_PRIORITY)
        # direct-deny, on the direct entrypoint.
        self.assertLess(WEBSITE_INFO_EXCEPTION_PRIORITY, 10000)

    def test_the_render_is_the_same_every_time(self):
        again = self.env["cloud.host"]._shipped_edge_guard_yml()
        self.assertEqual(again, self.document)
        self.assertEqual(edge_guard_digest(again), edge_guard_digest(self.document))
        self.assertRegex(edge_guard_digest(self.document), r"^[0-9a-f]{64}$")
